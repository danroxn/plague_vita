#!/usr/bin/env python3
"""Prepare Vita artwork, trophies and game identity once from the supported APK."""

from pathlib import Path
import argparse
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "work/assets"
APK_BYTES = 54207234
APK_XXH3_128 = "bf4c7699a451f8e550a3ff3edd21f541"
LIBRARY_SOURCE = "lib/armeabi-v7a/libgame.so"


def xxh3_128(path: Path) -> str:
    try:
        with path.open("rb") as source:
            result = subprocess.run(
                ["xxhsum", "-H128", "-"],
                stdin=source,
                check=True,
                capture_output=True,
                text=True,
            )
    except FileNotFoundError as error:
        if error.filename == "xxhsum":
            raise RuntimeError("xxhsum is missing; install xxhash or rebuild the devcontainer") from error
        raise
    except subprocess.CalledProcessError as error:
        raise RuntimeError(error.stderr.strip() or str(error)) from error
    checksum = result.stdout.partition(" ")[0]
    if len(checksum) != 32 or any(character not in "0123456789abcdef" for character in checksum):
        raise RuntimeError("Invalid XXH3-128 checksum output from xxhsum")
    return checksum


def write_game_data_header(apk: Path, output: Path) -> None:
    with zipfile.ZipFile(apk) as archive:
        library_bytes = archive.getinfo(LIBRARY_SOURCE).file_size
    (output / "game_data.h").write_text(
        "/* Generated by tools/prepare_assets.py. */\n"
        "#ifndef PORT_GENERATED_GAME_DATA_H\n"
        "#define PORT_GENERATED_GAME_DATA_H\n\n"
        f"#define EXPECTED_APK_BYTES {APK_BYTES}U\n"
        f'#define EXPECTED_APK_XXH3_128 "{APK_XXH3_128}"\n\n'
        f"#define PORT_LIBRARY_BYTES {library_bytes}U\n\n"
        "#endif\n",
        encoding="utf-8",
    )


def publish_outputs(staging_dir: Path, outputs: list[tuple[Path, Path]]) -> None:
    previous = staging_dir / "previous"
    previous.mkdir()
    published = []
    backups = []
    try:
        for index, (source, target) in enumerate(outputs):
            if target.exists() or target.is_symlink():
                backup = previous / str(index)
                os.replace(target, backup)
                backups.append((backup, target))
            os.replace(source, target)
            published.append(target)
    except BaseException:
        for target in reversed(published):
            if target.is_dir() and not target.is_symlink():
                shutil.rmtree(target)
            else:
                target.unlink()
        for backup, target in reversed(backups):
            os.replace(backup, target)
        raise


def prepare_assets(apk: Path, output: Path) -> None:
    from package_assets import generate_package_assets
    from package_trophies import generate_trophy_assets

    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="prepare-assets-", dir=output.parent) as temporary:
        staging_dir = Path(temporary)
        snapshot = staging_dir / "package.apk"
        shutil.copyfile(apk, snapshot)
        if snapshot.stat().st_size != APK_BYTES or xxh3_128(snapshot) != APK_XXH3_128:
            raise ValueError("Unsupported APK; Plague Inc. 1.15.3 (version code 75) is required")

        generated_dir = staging_dir / "generated"
        generate_package_assets(snapshot, generated_dir / "package")
        generate_trophy_assets(snapshot, generated_dir)
        write_game_data_header(snapshot, generated_dir)
        snapshot.unlink()

        # Publish complete assets only; the original APK stays at its source path.
        output.mkdir(exist_ok=True)
        publish_outputs(
            staging_dir,
            [
                (generated_dir / name, output / name)
                for name in ("package", "trophy", "trophy_catalog.h", "game_data.h")
            ],
        )
    print(f"Prepared Vita assets in {output}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apk", type=Path, required=True, help="Supported original APK")
    parser.add_argument(
        "--output", type=Path, default=DEFAULT_OUTPUT, help="Asset directory (default: work/assets)"
    )
    args = parser.parse_args()
    try:
        prepare_assets(args.apk.resolve(strict=True), args.output.resolve())
    except (ValueError, OSError, RuntimeError, KeyError, zipfile.BadZipFile) as error:
        print(f"Asset preparation failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
